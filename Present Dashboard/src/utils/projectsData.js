export const isUserAdmin = (user) => {
  if (!user) return false;
  if (user.isAdmin === true || user.is_admin === true) return true;
  const role = String(user.role || '').toLowerCase().trim();
  if (role === 'admin' || role === 'administrator' || role === 'superadmin') return true;
  const email = String(user.email || '').toLowerCase().trim();
  if (email === 'admin@nexus.com' || email.includes('admin')) return true;
  return false;
};

export const normalizeMemberName = (name) => {
  if (!name) return '';
  return name
    .toLowerCase()
    .replace(/^[a-z]\.\s*/i, '')
    .replace(/[^a-z0-9\s]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
};

export const getStoredTeamIdentity = () => {
  try {
    return localStorage.getItem('nexus_team_member_identity') || '';
  } catch (e) {
    return '';
  }
};

export const setStoredTeamIdentity = (name) => {
  try {
    if (name) localStorage.setItem('nexus_team_member_identity', name);
    else localStorage.removeItem('nexus_team_member_identity');
    window.dispatchEvent(new Event('nexus-data-updated'));
  } catch (e) {}
};

// Safe JSON parser helper for Arrays (handles single, double, and CSV strings)
export const safeJsonParse = (val, fallback = []) => {
  if (!val) return fallback;
  if (typeof val !== 'string') return val;
  try {
    return JSON.parse(val);
  } catch (e) {
    return fallback;
  }
};

export const safeJsonParseArray = (val, fallback = []) => {
  if (!val) return fallback;
  if (Array.isArray(val)) return val;
  if (typeof val === 'string') {
    const trimmed = val.trim();
    if (!trimmed) return fallback;
    if (trimmed.startsWith('[')) {
      try {
        let parsed = JSON.parse(trimmed);
        if (typeof parsed === 'string') parsed = JSON.parse(parsed);
        if (Array.isArray(parsed)) return parsed;
      } catch (e) {}
    }
    return trimmed.split(',').map(s => s.trim()).filter(Boolean);
  }
  return fallback;
};

export const isNexusAdmin = (name) => {
  if (!name) return false;
  const n = String(name).toLowerCase().replace(/[^a-z0-9]/g, '').trim();
  return n === 'nexusadmin' || n === 'admin' || n === 'sunnexus' || n === 'adminmaster' || n === 'useradmin' || n === 'nexus' || n === 'systemadmin' || n.includes('admin');
};

// Robust Team Member Parser (Enforces userId, fullName, email, avatar, role, branch, year, domain)
export const parseTeamMembers = (input) => {
  if (!input) return [];
  if (Array.isArray(input)) {
    return input.map(m => {
      if (typeof m === 'string') {
        const trimmed = m.trim();
        if (!trimmed) return null;
        return {
          userId: trimmed,
          id: trimmed,
          fullName: trimmed,
          name: trimmed,
          email: '',
          avatar: '',
          image: '',
          role: 'Contributor',
          branch: '',
          year: '',
          domain: ''
        };
      }
      if (m && typeof m === 'object') {
        const nameVal = (m.name || m.fullName || m.title || '').trim();
        const uId = m.userId || m.id || m.email || nameVal || 'anon_member';
        return {
          userId: uId,
          id: uId,
          fullName: nameVal,
          name: nameVal,
          email: m.email || '',
          avatar: m.avatar || m.image || '',
          image: m.image || m.avatar || '',
          role: m.role || 'Contributor',
          branch: m.branch || '',
          year: m.year || '',
          domain: m.domain || ''
        };
      }
      return null;
    }).filter(m => m && (m.userId || m.name) && !isNexusAdmin(m.name || m.fullName || m.userId));
  }
  if (typeof input === 'string') {
    const trimmed = input.trim();
    if (!trimmed) return [];
    if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        return parseTeamMembers(parsed);
      } catch (e) {
        // Fall through if invalid JSON string
      }
    }
    return trimmed.split(/[,;]/).map(item => {
      const nameStr = item.trim();
      if (!nameStr) return null;
      const match = nameStr.match(/^(.*?)\s*\((.*?)\)$/);
      const nameVal = match ? match[1].trim() : nameStr;
      const roleVal = match ? match[2].trim() : 'Contributor';
      return {
        userId: nameVal,
        id: nameVal,
        fullName: nameVal,
        name: nameVal,
        email: '',
        avatar: '',
        image: '',
        role: roleVal,
        branch: '',
        year: '',
        domain: ''
      };
    }).filter(Boolean);
  }
  return [];
};

const COMMON_TITLES = new Set(['reddy', 'rao', 'kumar', 'naidu', 'krishna', 'prasad', 'varma', 'chowdary']);

// Helper to check if a user is a team member of a project (Primary match on userId / id)
export const isUserInProjectTeam = (user, project, customMemberName = '') => {
  if (!project) return false;

  const teamList = parseTeamMembers(project.team || project.teamMembers || project.team_members);
  if (!teamList || teamList.length === 0) return false;

  const loggedInId = String(user?.id || user?.userId || '').toLowerCase().trim();
  const loggedInEmail = String(user?.email || '').toLowerCase().trim();
  const loggedInName = String(user?.name || user?.fullName || user?.firstName || user?.username || '').toLowerCase().trim();

  const storedId = String(getStoredTeamIdentity() || '').toLowerCase().trim();
  const customId = String(customMemberName || '').toLowerCase().trim();
  const targetId = customId || storedId;

  return teamList.some(m => {
    const mUserId = String(m.userId || m.id || '').toLowerCase().trim();
    const mEmail = String(m.email || '').toLowerCase().trim();
    const mName = String(m.fullName || m.name || '').toLowerCase().trim();

    // 1. Primary: userId / id match
    if (loggedInId && mUserId && (mUserId === loggedInId || mUserId.includes(loggedInId) || loggedInId.includes(mUserId))) return true;
    if (targetId && mUserId && (mUserId === targetId || mUserId.includes(targetId) || targetId.includes(mUserId))) return true;

    // 2. Email match
    if (loggedInEmail && mEmail && mEmail === loggedInEmail) return true;
    if (loggedInEmail && mUserId && mUserId === loggedInEmail) return true;

    // 3. Normalized Name match for backward compatibility
    if (loggedInName && mName && (mName === loggedInName || (loggedInName.length > 3 && mName.includes(loggedInName)))) return true;
    if (targetId && mName && (mName === targetId || mName.includes(targetId))) return true;

    // 4. Distinct token match
    const targetNorm = normalizeMemberName(targetId || loggedInName);
    const memberNorm = normalizeMemberName(mName);
    if (targetNorm && memberNorm) {
      if (targetNorm === memberNorm) return true;
      const targetDistinct = targetNorm.split(' ').filter(w => w.length > 2 && !COMMON_TITLES.has(w));
      const memberDistinct = memberNorm.split(' ').filter(w => w.length > 2 && !COMMON_TITLES.has(w));
      if (targetDistinct.length > 0 && memberDistinct.length > 0) {
        if (targetDistinct.some(tw => memberDistinct.some(mw => mw === tw || (mw.length > 4 && tw.length > 4 && (mw.includes(tw) || tw.includes(mw)))))) return true;
      }
    }

    return false;
  });
};
